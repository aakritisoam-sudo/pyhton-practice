## for loop with lists
l = [1,4,6,234,6,764]

for i in l:
    print(i)

## for loop with tuple
t = (1,4,6,231,122)
for i in t:
    print(i)  # iterates through the tuple and prints each elements(iterate means to go through each element one by one)

## for loop with string
s = "aakriti"
for i in s:
    print(i) 


