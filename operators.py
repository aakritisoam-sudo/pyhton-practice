# Arithmetic operators 

a = 34
b = 4
c = a+b #addition
print(c)

# Assignment operators 
a = 4-2 # Assign 4-2 to a
print(a)
b = 3
b += 3 # Increment b by 3 and then assign it to b 
b -= 2 # Decrement b by 2 and then assign it to b 
print(b)

# Comparison operators 

d = 5<4 #less than operator 
print(d) #comparison operators return boolean values 

d = 5>=3 #greater than or equal to operator
print(d)

d =5!= 5 #not equal to operator 
print(d)

d = 5==5 #equal to operator 
print(d) 

# Logical operators 

e = True or False #logical or operator 
print(e)

e = True and False #logical and operator
print(e)

print("True or False is", True or False)
print("True and False is", True and False)
print("False or False is", False or False)
print("False and False is", False and False)